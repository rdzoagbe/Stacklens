// ============================================================================
// LIVE TRANSLATION SYSTEM
// 1. Uses manual translations first (from above)
// 2. Falls back to cached auto-translations (localStorage)
// 3. Batch-translates missing keys via AI on first load per language
// ============================================================================

const TRANS_CACHE_KEY = 'ag_live_translations';
const TRANS_QUEUE_DELAY = 2000; // Wait 2s to batch multiple missing keys

// Load cached translations from localStorage
function loadTransCache() {
  try {
    return JSON.parse(localStorage.getItem(TRANS_CACHE_KEY) || '{}');
  } catch { return {}; }
}

// Save translations to localStorage cache
function saveTransCache(cache) {
  try {
    localStorage.setItem(TRANS_CACHE_KEY, JSON.stringify(cache));
  } catch {}
}

// Queue for batch translation
let _transQueue = {};
let _transTimer = null;
let _transCallbacks = [];
let _translating = false;

async function flushTranslationQueue() {
  if (_translating) return;
  
  const queued = { ..._transQueue };
  _transQueue = {};
  _translating = true;

  // Group by target language
  const byLang = {};
  for (const [cacheKey, { key, enValue, lang }] of Object.entries(queued)) {
    if (!byLang[lang]) byLang[lang] = [];
    byLang[lang].push({ key, enValue, cacheKey });
  }

  const cache = loadTransCache();

  for (const [lang, items] of Object.entries(byLang)) {
    if (items.length === 0) continue;
    
    const langNames = { fr: 'French', es: 'Spanish', de: 'German', pt: 'Portuguese', it: 'Italian', nl: 'Dutch', ja: 'Japanese', zh: 'Chinese', ko: 'Korean', ar: 'Arabic' };
    const langName = langNames[lang] || lang;
    
    // Build a simple key:value map for the AI to translate
    const toTranslate = {};
    items.forEach(({ key, enValue }) => {
      toTranslate[key] = enValue;
    });

    try {
      // Call the AI proxy directly via the imported function
      const result = await callAI({
        system: `You are a professional translator. Translate the following UI labels from English to ${langName}. Return ONLY a valid JSON object with the same keys and translated values. Keep translations concise — these are button labels, menu items, and short phrases for a SaaS management app. Do not add explanations.`,
        messages: [{ role: 'user', content: JSON.stringify(toTranslate) }],
        max_tokens: 4000,
      });

      // Parse the AI response
      const text = result.choices?.[0]?.message?.content || result.content?.[0]?.text || '';
      const jsonMatch = text.match(/\{[\s\S]*\}/);
      if (jsonMatch) {
        const translated = JSON.parse(jsonMatch[0]);
        if (!cache[lang]) cache[lang] = {};
        
        for (const [k, v] of Object.entries(translated)) {
          cache[lang][k] = v;
        }
        
        saveTransCache(cache);
        console.log(`✅ Live-translated ${Object.keys(translated).length} keys to ${langName}`);
        
        // Notify React to re-render
        _transCallbacks.forEach(cb => cb());
      }
    } catch (err) {
      console.warn(`Live translation failed for ${langName}:`, err.message);
      // Fallback: use simple word-level translation for common UI terms
      if (!cache[lang]) cache[lang] = {};
      items.forEach(({ key, enValue }) => {
        // At minimum, keep the English value so it doesn't show as a raw key
        if (!cache[lang][key]) cache[lang][key] = enValue;
      });
      saveTransCache(cache);
    }
  }

  _translating = false;
}

function queueForTranslation(key, enValue, lang) {
  const cacheKey = `${lang}:${key}`;
  _transQueue[cacheKey] = { key, enValue, lang };
  
  if (_transTimer) clearTimeout(_transTimer);
  _transTimer = setTimeout(flushTranslationQueue, TRANS_QUEUE_DELAY);
}

// React hook version that triggers re-render when translations arrive
import { useState, useEffect, useCallback } from 'react';
import { callAI } from './firebase-config';

export function useTranslation(language = 'en') {
  const [, forceUpdate] = useState(0);
  
  useEffect(() => {
    const cb = () => forceUpdate(n => n + 1);
    _transCallbacks.push(cb);
    return () => {
      _transCallbacks = _transCallbacks.filter(x => x !== cb);
    };
  }, []);

  const lang = translations[language] || {};
  const en = translations.en || {};
  const cache = loadTransCache();
  const cached = cache[language] || {};

  return useCallback((key) => {
    // 1. Manual translation exists for this language
    if (lang[key] !== undefined) return lang[key];
    
    // 2. Cached auto-translation exists
    if (cached[key] !== undefined) return cached[key];
    
    // 3. English fallback exists — queue for translation
    if (en[key] !== undefined) {
      if (language !== 'en') {
        queueForTranslation(key, en[key], language);
      }
      return en[key]; // Show English while translating
    }
    
    // 4. Key not found anywhere — return the key itself
    return key;
  }, [language, lang, cached, en]);
}
